package build

import (
	"encoding/json"
	"fmt"
	"strconv"
	"strings"

	"catty/internal/aot"
)

const generatedFileName = "generated.go"

// Options are the catty build command's inputs.
type Options struct {
	Classpath       []string
	Main            string
	Mode            string
	PolicyPath      string
	ReportPath      string
	OutputPath      string
	GeneratedSource string
	EnablePlugins   bool
	EnableThreads   bool
	EnableLifecycle bool
}

// generateSource renders the standalone application module: an embedded image
// specification, an entry table, and one real Go body per AOT method.
func (b *Build) generateSource() (mainSource, generatedSource string, err error) {
	var funcs strings.Builder
	funcs.WriteString("package main\n\n")
	if len(b.aot) > 0 {
		funcs.WriteString("import \"catty/rt\"\n\n")
	}
	for i, entry := range b.aot {
		if entry.symbol != fmt.Sprintf("cattyMethod%d", i) {
			return "", "", fmt.Errorf("catty: internal error: AOT entry order mismatch")
		}
		code, err := aot.Generate(entry.symbol, entry.method, entry.heights, entry.shapes)
		if err != nil {
			return "", "", fmt.Errorf("catty: %s.%s%s: %w", entry.class.Name, entry.method.Name, entry.method.Descriptor, err)
		}
		funcs.WriteString(code)
		funcs.WriteString("\n")
	}

	imageJSON, err := json.Marshal(b.image)
	if err != nil {
		return "", "", fmt.Errorf("catty: cannot encode image: %w", err)
	}
	var main strings.Builder
	main.WriteString("// Code generated by catty. DO NOT EDIT.\n")
	main.WriteString("package main\n\n")
	if b.profile.Plugins {
		main.WriteString("import (\n\t\"fmt\"\n\t\"os\"\n\n\t\"catty/plugin\"\n\t\"catty/rt\"\n)\n\n")
	} else {
		main.WriteString("import (\n\t\"fmt\"\n\t\"os\"\n\n\t\"catty/rt\"\n)\n\n")
	}
	fmt.Fprintf(&main, "const cattyImageJSON = %s\n\n", strconv.Quote(string(imageJSON)))
	main.WriteString("var cattyEntries = []rt.Entry{")
	for i := range b.aot {
		if i > 0 {
			main.WriteString(", ")
		}
		main.WriteString(fmt.Sprintf("cattyMethod%d", i))
	}
	main.WriteString("}\n\n")
	main.WriteString("func main() {\n")
	if b.profile.Plugins {
		main.WriteString("\trt.SetAdmission(plugin.Admit)\n")
	}
	main.WriteString("\timage, err := rt.DecodeImage([]byte(cattyImageJSON), cattyEntries)\n")
	main.WriteString("\tif err != nil {\n\t\tfmt.Fprintln(os.Stderr, err)\n\t\tos.Exit(2)\n\t}\n")
	main.WriteString("\tos.Exit(rt.RunApp(image, os.Args[1:]))\n")
	main.WriteString("}\n")
	return main.String(), funcs.String(), nil
}

// moduleFile renders the temporary generated module that links the local
// runtime checkout.
func moduleFile(moduleRoot string) string {
	return fmt.Sprintf("module cattyapp\n\ngo 1.21\n\nrequire catty v0.0.0\n\nreplace catty => %s\n",
		strconv.Quote(moduleRoot))
}

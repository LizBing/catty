// Command gen emits the repetitive probe files used by the gcopt benchmarks:
//
//   - q1_devirt/budget_gen.go  : Adder methods of increasing size to locate the
//     inliner's cost budget boundary (gc uses an 80-unit budget).
//   - q3_bigfunc/big_gen.go    : large straight-line functions for the
//     "one big function vs split" and size-scaling probes.
//
// Run from the module root:  go run ./gen
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if err := genBudget(); err != nil {
		panic(err)
	}
	if err := genBig(); err != nil {
		panic(err)
	}
	fmt.Println("generated q1_devirt/budget_gen.go and q3_bigfunc/big_gen.go")
}

func write(path, body string) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(body), 0o644)
}

// genBudget emits methods M00..M40 on *C1 with 0..40 statements so the -m
// inliner report pins down exactly where "cost exceeds budget 80" begins.
func genBudget() error {
	var b strings.Builder
	b.WriteString("// Code generated by gen/main.go.\n\npackage q1_devirt\n\n")
	for n := 0; n <= 40; n++ {
		fmt.Fprintf(&b, "// M%02d has %d statement(s); used to locate the inliner budget boundary.\n", n, n)
		fmt.Fprintf(&b, "func (c *C1) M%02d(x int64) int64 {\n", n)
		for i := 1; i <= n; i++ {
			fmt.Fprintf(&b, "\tx = x*2 + int64(%d)\n", i)
		}
		b.WriteString("\treturn x\n}\n\n")
	}
	return write("q1_devirt/budget_gen.go", b.String())
}

// genBig emits BigChainN (one straight-line dependent chain of N steps) and
// SmallChainA..SmallChainH (25 steps each, used for the split comparison).
func genBig() error {
	var b strings.Builder
	b.WriteString("// Code generated by gen/main.go.\n\npackage q3_bigfunc\n\n")

	// Small reusable chains for the "split into sub-functions" candidate. The
	// XOR-shift step is deliberately nonlinear so gc cannot fold the whole
	// dependent chain into a single multiply (a pure LCG affine chain does get
	// folded — see R-0003 Q3 note).
	step := func(i int) string {
		return fmt.Sprintf("x = x*1103515245 + %d; x ^= x >> 16", i+12345)
	}
	for k := 0; k < 8; k++ {
		name := byte('A' + k)
		fmt.Fprintf(&b, "func SmallChain%c(x int64) int64 {\n", name)
		for i := 0; i < 25; i++ {
			fmt.Fprintf(&b, "\t%s\n", step(i))
		}
		b.WriteString("\treturn x\n}\n\n")
	}

	sizes := []int{50, 100, 200, 500, 1000, 2000, 4000}
	for _, n := range sizes {
		fmt.Fprintf(&b, "// BigChain%d is a single %d-step dependent chain.\n", n, n)
		fmt.Fprintf(&b, "func BigChain%d(x int64) int64 {\n", n)
		for i := 0; i < n; i++ {
			fmt.Fprintf(&b, "\t%s\n", step(i%1000))
		}
		b.WriteString("\treturn x\n}\n\n")
	}

	// Split candidate: compose the eight 25-step small chains in sequence so the
	// total work equals BigChain200 without being one giant body.
	b.WriteString("func SplitChain200(x int64) int64 {\n")
	order := []byte{'A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'}
	cur := "x"
	for _, c := range order {
		next := fmt.Sprintf("SmallChain%c(%s)", c, cur)
		cur = next
	}
	fmt.Fprintf(&b, "\treturn %s\n}\n\n", cur)

	return write("q3_bigfunc/big_gen.go", b.String())
}
